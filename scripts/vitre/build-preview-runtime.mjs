// Regenerate the native browser's Playwright selector engine from the pinned
// installed dependency, using the same extraction as Desktop's host.
import * as NodeModule from "node:module";
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";
import * as NodeVM from "node:vm";
const require = NodeModule.createRequire(new URL("../package.json", import.meta.url));
const path = NodePath.resolve(
  NodePath.dirname(require.resolve("playwright-core/package.json")),
  "lib/coreBundle.js",
);
const bundle = await NodeFSP.readFile(path, "utf8");
const marker = "source3 = ";
const start = bundle.indexOf(marker);
const end = bundle.indexOf(";\n  }\n});", start + marker.length);
if (start < 0 || end < 0) throw new Error("Pinned Playwright runtime source markers changed");
const source = NodeVM.runInNewContext(
  bundle.slice(start + marker.length, end),
  Object.create(null),
  {
    timeout: 1000,
  },
);
if (typeof source !== "string" || source.length < 100000)
  throw new Error("Invalid Playwright runtime source");
const options = {
  isUnderTest: false,
  sdkLanguage: "javascript",
  testIdAttributeName: "data-testid",
  stableRafCount: 1,
  browserName: "webkit",
  shouldPrependErrorPrefix: false,
  isUtilityWorld: false,
  customEngines: [],
};
const output = new URL("../../crates/vitre-app/assets/preview-runtime.js", import.meta.url);
await NodeFSP.mkdir(NodePath.dirname(output.pathname), { recursive: true });
await NodeFSP.writeFile(
  new URL("preview-runtime.LICENSE", output),
  await NodeFSP.readFile(
    NodePath.resolve(NodePath.dirname(require.resolve("playwright-core/package.json")), "LICENSE"),
  ),
);
await NodeFSP.writeFile(
  output,
  `// Generated by scripts/vitre/build-preview-runtime.mjs from playwright-core (Apache-2.0).\n(() => {if(globalThis.__t3PlaywrightInjected)return; const module={exports:{}};\n${source}\nglobalThis.__t3PlaywrightInjected=new (module.exports.InjectedScript())(globalThis,${JSON.stringify(options)});})();\n`,
);
