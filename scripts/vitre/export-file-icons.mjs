// Export the web client's installed Pierre/T3 icon set for native GPUI.
// Prints an apply_patch patch; --check verifies the checked-in export instead.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getBuiltInSpriteSheet } from "../../apps/web/node_modules/@pierre/trees/dist/builtInIcons.js";
import treeStyles from "../../apps/web/node_modules/@pierre/trees/dist/style.js";
import { T3_PIERRE_ICONS, resolvePierreIconForEntry } from "../../apps/web/src/pierre-icons.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const upstream = "apps/web/node_modules/@pierre/trees";
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const source = read(`${upstream}/dist/builtInIcons.js`);
const table = (name) => {
  const match = source.match(new RegExp(`const ${name} = (\\{[\\s\\S]*?\\n\\});`));
  if (!match) throw new Error(`Missing upstream table ${name}`);
  return JSON.parse(match[1].replace(/^(\s*)([a-zA-Z_][\w-]*):/gm, '$1"$2":'));
};
const builtInNames = table("BUILT_IN_FILE_NAME_TOKENS");
const builtInExtensions = {
  ...table("BUILT_IN_FILE_EXTENSION_TOKENS"),
  ...table("COMPLETE_EXTENSION_OVERRIDES"),
};
// The artwork uses currentColor; its language palette lives in the shadow-DOM
// stylesheet, not in the sprite. Resolve that CSS here for standalone SVGs.
const palette = Object.fromEntries(
  [
    ...treeStyles.matchAll(/--trees-icon-([\w-]+):\s*light-dark\((#[\da-f]+),\s*(#[\da-f]+)\)/gi),
  ].map(([, name, light, dark]) => [name, { light, dark }]),
);
const tokenColours = Object.fromEntries(
  [
    ...treeStyles.matchAll(
      /--trees-file-icon-color-([\w-]+):\s*var\(\s*--trees-file-icon-color,\s*var\(--trees-icon-([\w-]+)\)\s*\)/g,
    ),
  ].map(([, token, colour]) => [token, colour]),
);
if (!palette.cyan || tokenColours.react !== "cyan")
  throw new Error("Upstream icon palette changed; update the native exporter");
const builtin = (rules) =>
  Object.fromEntries(Object.entries(rules).map(([k, v]) => [k, `file-tree-builtin-${v}`]));
const rules = {
  CUSTOM_NAMES: T3_PIERRE_ICONS.byFileName,
  CUSTOM_EXTENSIONS: T3_PIERRE_ICONS.byFileExtension,
  BUILTIN_NAMES: builtin(builtInNames),
  BUILTIN_EXTENSIONS: builtin(builtInExtensions),
};
if (T3_PIERRE_ICONS.byFileNameContains || T3_PIERRE_ICONS.remap)
  throw new Error("New web resolver features need a native port");
const symbols = new Map();
for (const match of `${getBuiltInSpriteSheet("complete")}${T3_PIERRE_ICONS.spriteSheet}`.matchAll(
  /<symbol\s+id="([^"]+)"\s+viewBox="([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g,
)) {
  symbols.set(match[1], { viewBox: match[2], body: match[3].trim() });
}
const ids = [
  ...new Set(["file-tree-builtin-default", ...Object.values(rules).flatMap(Object.values)]),
].sort();
const files = {};
const assetLines = [];
for (const id of ids) {
  const symbol = symbols.get(id);
  if (!symbol) throw new Error(`Missing icon ${id}`);
  if (/var\(|<script|<foreignObject|href=/i.test(symbol.body))
    throw new Error(`Non-standalone icon ${id}`);
  for (const [theme, fallback] of [
    ["dark", "#cbd5e1"],
    ["light", "#475569"],
  ]) {
    const token = id.replace("file-tree-builtin-", "");
    const ink = tokenColours[token] ? palette[tokenColours[token]][theme] : fallback;
    const name = `${theme}/${id}.svg`;
    files[`crates/vitre-app/icons/file-types/${name}`] =
      `<!-- Adapted from T3/Pierre for standalone native rendering; see ../NOTICE.md. -->\n<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="${symbol.viewBox}" color="${ink}" fill="${ink}">${symbol.body}</svg>\n`;
    assetLines.push(
      `    ("file-icons/${name}", include_bytes!("../../icons/file-types/${name}")),`,
    );
  }
}
const rustRules = Object.entries(rules)
  .map(
    ([name, rules]) =>
      `pub(super) const ${name}: &[(&str, &str)] = &[\n${Object.entries(rules)
        .sort(([a], [b]) => a.localeCompare(b, "en"))
        .map(([k, v]) => `    (${JSON.stringify(k)}, ${JSON.stringify(v)}),`)
        .join("\n")}\n];`,
  )
  .join("\n\n");
// Verify enough input examples to catch precedence and multipart-extension drift.
const cases = [
  ...new Set([
    ...Object.keys(rules.CUSTOM_NAMES),
    ...Object.keys(rules.BUILTIN_NAMES),
    ...Object.keys({ ...rules.BUILTIN_EXTENSIONS, ...rules.CUSTOM_EXTENSIONS }).map(
      (e) => `example.${e}`,
    ),
    "unknown.zzz",
    "folder/main.test.tsx",
  ]),
].map((name) => [name, resolvePierreIconForEntry(name, "file")?.name]);
files["crates/vitre-app/src/icons/file_types.rs"] =
  `// Generated by scripts/vitre/export-file-icons.mjs; do not edit.\n// Pierre Apache-2.0 + T3 MIT; see icons/file-types/NOTICE.md.\n\n${rustRules}\n\npub(super) const ASSETS: &[(&str, &[u8])] = &[\n${assetLines.join("\n")}\n];\n\n#[cfg(test)]\npub(super) const WEB_CASES: &[(&str, &str)] = &[\n${cases.map(([k, v]) => `    (${JSON.stringify(k)}, ${JSON.stringify(v)}),`).join("\n")}\n];\n`;
files["crates/vitre-app/icons/file-types/LICENSE-APACHE.md"] = read(`${upstream}/LICENSE.md`);
files["crates/vitre-app/icons/file-types/NOTICE.md"] =
  `# Native file icons\n\nExported from the installed @pierre/trees ${JSON.parse(read(`${upstream}/package.json`)).version} (Apache-2.0, Copyright 2025 Pierre Computer Company), combined with T3's MIT custom icons in apps/web/src/pierre-icons.ts. Only SVG artwork and filename/extension lookup tables are included; no web tree runtime or new dependency.\n\nLocal adaptations: standalone 32px SVG documents, explicit light/dark currentColor, and native embedded-asset lookup tables. Regenerate with Node 24: node scripts/vitre/export-file-icons.mjs (prints an apply_patch patch); verify with --check. Rustfmt may be applied to the generated Rust file.\n\n## Upstream notice\n\n${read(`${upstream}/NOTICE.md`)}`;
// Rustfmt changes layout only; compare generated Rust after stripping whitespace.
const equivalent = (name, a, b) =>
  name.endsWith(".rs")
    ? a.replace(/\s/g, "").replace(/,([)\]])/g, "$1") ===
      b.replace(/\s/g, "").replace(/,([)\]])/g, "$1")
    : a === b;
const changed = Object.entries(files).filter(
  ([name, contents]) =>
    !fs.existsSync(path.join(root, name)) || !equivalent(name, read(name), contents),
);
if (process.argv.includes("--check")) {
  if (changed.length)
    throw new Error(`Native icon export is stale: ${changed.map(([name]) => name).join(", ")}`);
  console.log(
    `Verified ${ids.length} icons, ${cases.length} web/native resolver cases, and both themes.`,
  );
} else {
  const patch = changed.map(([name, contents]) =>
    fs.existsSync(path.join(root, name))
      ? `*** Update File: ${name}\n@@\n${read(name)
          .trimEnd()
          .split("\n")
          .map((l) => `-${l}`)
          .join("\n")}\n${contents
          .trimEnd()
          .split("\n")
          .map((l) => `+${l}`)
          .join("\n")}`
      : `*** Add File: ${name}\n${contents
          .trimEnd()
          .split("\n")
          .map((l) => `+${l}`)
          .join("\n")}`,
  );
  process.stdout.write(`*** Begin Patch\n${patch.join("\n")}\n*** End Patch\n`);
}
